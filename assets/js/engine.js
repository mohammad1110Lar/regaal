  // تکه‌ی اصلی و چند نتیجه‌ی اول از رنگ محبوب، اگر چنین کالایی در نامزدهای مناسب هست
  function likeFirst(scored, intent) {
    const ok = (intent.likeColors || []).filter((c) => !unsuitableColors(intent).includes(c));
    if (!ok.length || intent.colors.length || !scored.length) return { list: scored.map((x) => x[1]), found: null };
    const top = scored[0][0];
    const liked = scored.filter(([s, it]) => !it._acc && ok.includes(it._fam) && s >= top * 0.45).map((x) => x[1]);
    if (!liked.length) return { list: scored.map((x) => x[1]), found: false };
    const rest = scored.map((x) => x[1]).filter((x) => !liked.includes(x));
    // یک در میان: رنگ محبوب، بعد بهترین بقیه؛ تا نیمی از نتیجه‌های اول رنگ محبوب باشد
    const list = [];
    for (let k = 0; list.length < 12 && (k < liked.length || k < rest.length); k++) {
      if (liked[k]) list.push(liked[k]);
      if (rest[k]) list.push(rest[k]);
    }
    return { list: list.concat(liked.slice(12), rest.slice(12)).filter((x, k, a) => a.indexOf(x) === k), found: true };
  }

  // تنوع: از هر کد مدل حداکثر یک رنگ و از هر نوع حداکثر چند تا پشت سر هم
  // و از هر فروشگاه حداکثر سهمی از نتایج، تا پیشنهادها از جاهای مختلف باشند
  function diversify(list, n, perType) {
    const out = [], styles = new Set(), typeCount = {}, storeCount = {};
    const perStore = STORE_COUNT > 2 ? Math.max(2, Math.ceil(n * 0.4)) : n;
    for (const it of list) {
      if (out.length >= n) break;
      if (styles.has(it.style)) continue;
      if (perType && (typeCount[it.type] || 0) >= perType) continue;
      if ((storeCount[it.store] || 0) >= perStore) continue;
      styles.add(it.style);
      typeCount[it.type] = (typeCount[it.type] || 0) + 1;
      storeCount[it.store] = (storeCount[it.store] || 0) + 1;
      out.push(it);
    }
    if (out.length < n) for (const it of list) { if (out.length >= n) break; if (!out.includes(it) && !styles.has(it.style)) { styles.add(it.style); out.push(it); } }
    return out;
  }

