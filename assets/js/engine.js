  // حذف یک برداشت با کلیک کاربر روی ×
  function dropFrom(intent, keys) {
    if (!keys || !keys.length) return intent;
    const i = Object.assign({}, intent);
    for (const k of keys) {
      const [a, b, c] = k.split(":");
      if (k === "occasion") { i.occasion = null; i.season = null; i.rain = false; }
      else if (k === "gender") { i.genders = []; i.genderDropped = true; }
      else if (a === "type") i.types = i.types.filter((t) => t !== b);
      else if (k === "denim") i.denim = false;
      else if (a === "color") i.colors = i.colors.filter((x) => x !== b);
      else if (k === "mood") { i.colorMood = null; i.moodKey = null; }
      else if (a === "fit") i.fits = i.fits.filter((x) => x !== b);
      else if (a === "material") i.materials = i.materials.filter((x) => x !== b);
      else if (a === "pattern") i.patterns = i.patterns.filter((x) => x !== b);
      else if (a === "not" && b === "color") i.notColors = i.notColors.filter((x) => x !== c);
      else if (a === "not" && b === "type") i.notTypes = i.notTypes.filter((x) => x !== c);
      else if (k === "not:denim") i.notDenim = false;
      else if (a === "not" && b === "material") i.notMaterials = i.notMaterials.filter((x) => x !== c);
      else if (a === "not" && b === "pattern") i.notPatterns = i.notPatterns.filter((x) => x !== c);
      else if (a === "not" && b === "fit") i.notFits = i.notFits.filter((x) => x !== c);
      else if (a === "not" && b === "word") i.notKeywords = (i.notKeywords || []).filter((x) => x !== c);
      else if (k === "formality") i.formality = null;
      else if (k === "budget") { i.priceMax = null; i.cheap = false; i.budget = null; }
      else if (k === "classic") i.classic = false;
      else if (k === "noacc") i.noAcc = false;
      else if (k === "like") i.likeColors = [];
      else if (a === "pfit") i.prefFits = (i.prefFits || []).filter((x) => x !== b);
      else if (k === "size") i.size = null;
      else if (k === "age") i.age = null;
      else if (["sale", "modest", "comfy", "trendy", "rain", "skin", "body", "season"].includes(k)) i[k] = k === "skin" || k === "body" || k === "season" ? null : false;
    }
    return i;
  }

