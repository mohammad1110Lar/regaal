  function buildLook(anchor, intent) {
    if (!anchor || anchor._acc || anchor.type === "set" || anchor.type === "kids") return anchor ? [anchor] : [];
    const look = [anchor];
    const used = new Set(anchor.type === "dress" ? ["top", "bottom"] : [slotOf(anchor.type)]);
    const gender = anchor.gender;
    const wanted = ["top", "bottom"].concat(needsOuter(gender, intent, anchor) ? ["outer"] : []).filter((s) => !used.has(s));
    const base = Object.assign({}, intent, { types: [], colors: [], colorMood: null, fits: [], genders: [gender], keywords: [], denim: false, priceMax: null });
    const season = intent.season || intent.nowSeason;
    // بودجه‌ی کل: ۸۰٪ برای لباس‌ها، بقیه برای اکسسوری؛ برای تکه‌های باقیمانده هم جا بگذار
    const forPieces = intent.budget ? intent.budget * (intent.noAcc ? 1 : 0.8) : Infinity;
    wanted.forEach((slot, k) => {
      const cap = forPieces - look.reduce((sum, x) => sum + x.price, 0) - (wanted.length - k - 1) * 1.2e6;
      // با مانتو یا لایه‌ی رویی، شلوارک برای خانم‌ها جور نیست
      const noShorts = gender === "W" && wanted.includes("outer");
      const pool = ITEMS.filter((it) => !it._acc && !it._minor && (it.gender === gender || it.gender === "U") && slotOf(it.type) === slot && it.style !== anchor.style &&
        !(noShorts && it.type === "shorts") && it.price <= cap);
      let best = null, bestS = -1;
      for (const it of pool) {
        let s = scoreItem(it, base, { loose: true });
        if (s < 0) continue;
        const h = Math.min(...look.map((x) => harmony(x._fam, it._fam)));
        s = s * 0.6 + h * 42;
        // حداکثر یک رنگ شاخص در ست
        if (it._fam && !NEUTRALS.has(it._fam) && accentsOf(look).length && !accentsOf(look).includes(it._fam)) s -= 22;
        if (slot === "bottom" && SLOTS.top.includes(anchor.type) && it._denim && !intent.occasion) s += 8;
        // لایه‌ی رویی خانم‌ها: در فصل گرم مانتوی سبک، در سرما کاپشن یا پالتو
        if (slot === "outer" && gender === "W") {
          if (season === "warm" && it.type === "manto") s += 14;
          if (season === "cold" && ["jacket", "coat"].includes(it.type)) s += 10;
          if (["uni", "office", "pilgrimage", "mourning", "nowruz"].includes(intent.occasion) && it.type === "manto") s += 16;
        }
        if (slot === "outer" && gender === "M" && intent.occasion === "office" && it.type === "suit") s += 14;
        if (s > bestS) { bestS = s; best = it; }
      }
      if (best) { look.push(best); used.add(slot); }
    });
    // اول همان تکه‌ای که کاربر دنبالش بود، بعد بقیه از بالا به پایین
    const order = { outer: 0, top: 1, bottom: 2 };
    return [anchor].concat(look.slice(1).sort((a, b) => (order[slotOf(a.type)] ?? 3) - (order[slotOf(b.type)] ?? 3)));
  }

