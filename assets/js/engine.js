  function tailorQuery(text) {
    let t = " " + normalize(text) + " ";
    const en = [], labels = [];
    let garment = null, men = false;
    for (const [fa, word, kind] of TAILOR_WORDS) {
      const hit = fa.map(normalize).find((w) => t.includes(" " + w + " ") || t.includes(" " + w + "ی ") || t.includes(" " + w + "های "));
      if (!hit) continue;
      t = t.split(" " + hit).join(" "); // واژه‌ی گرفته‌شده دوباره (مثلاً «پیراهن» داخل «پیراهن مجلسی») گرفته نشود
      if (kind === "m") { men = true; continue; }
      if (kind === "w") continue;
      if (kind === "g") { if (garment) continue; garment = word; }
      if (!en.includes(word)) { en.push(word); labels.push(fa[0]); }
    }
    // واژه‌های لاتین (اگر کاربر خودش انگلیسی نوشته) هم می‌مانند
    (String(text).match(/[a-z][a-z-]{2,}/gi) || []).forEach((w) => { if (!en.includes(w.toLowerCase())) en.push(w.toLowerCase()); });
    if (men && garment === "dress") en[en.indexOf("dress")] = "shirt";
    if (!garment && !en.some((w) => /dress|skirt|suit|coat|blouse|top|pants|trousers|jumpsuit|shirt|gown/.test(w))) en.push(men ? "men outfit" : "dress");
    else if (men) en.unshift("men");
    return { en: en.slice(0, 9).join(" "), labels, garment, men };
  }

