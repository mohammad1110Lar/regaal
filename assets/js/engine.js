  function mergeIntent(next, prev) {
    if (!prev) return next;
    const isRefinement = !next.types.length && !next.occasion && !next.accOnly &&
      (next.colors.length || next.colorMood || next.fits.length || next.cheap || next.sale || next.priceMax || next.genders.length || next.materials.length ||
        next.patterns.length || next.more || next.wantLook || next.notColors.length || next.notTypes.length || next.notDenim || next.formality != null || next.simple || next.modest);
    if (!isRefinement) return next;
    const pick = (k) => (next[k] && next[k].length ? next[k] : prev[k] || []);
    return Object.assign({}, prev, {
      raw: prev.raw + " — " + next.raw,
      genders: pick("genders"), colors: pick("colors"), fits: pick("fits"), materials: pick("materials"), patterns: pick("patterns"),
      colorMood: next.colorMood || (next.colors.length ? null : prev.colorMood), moodKey: next.moodKey || prev.moodKey,
      notColors: (prev.notColors || []).concat(next.notColors), notTypes: (prev.notTypes || []).concat(next.notTypes), notFits: (prev.notFits || []).concat(next.notFits),
      notMaterials: (prev.notMaterials || []).concat(next.notMaterials), notPatterns: (prev.notPatterns || []).concat(next.notPatterns), notDenim: prev.notDenim || next.notDenim,
      notKeywords: (prev.notKeywords || []).concat(next.notKeywords || []),
      cheap: next.cheap || prev.cheap, sale: next.sale || prev.sale, priceMax: next.priceMax || prev.priceMax,
      formality: next.formality != null ? next.formality : prev.formality, simple: next.simple || prev.simple, modest: next.modest || prev.modest,
      wantLook: next.wantLook || prev.wantLook, more: next.more, keywords: prev.keywords.concat(next.keywords), refined: true,
    });
  }

