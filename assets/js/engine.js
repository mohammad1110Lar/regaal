  const PAIRS = [["navy", "cream"], ["navy", "white"], ["navy", "brown"], ["brown", "cream"], ["brown", "green"], ["brown", "blue"], ["green", "cream"],
    ["green", "pink"], ["green", "purple"], ["grey", "pink"], ["grey", "purple"], ["grey", "red"], ["grey", "blue"], ["cream", "red"],
    ["blue", "yellow"], ["blue", "white"], ["red", "navy"], ["yellow", "black"], ["yellow", "white"], ["yellow", "navy"], ["orange", "navy"], ["purple", "cream"]];
  const isPair = (a, b) => PAIRS.some(([x, y]) => (x === a && y === b) || (x === b && y === a));

  function harmony(a, b) {
    if (!a || !b) return 0.6;
    if (a === b) return NEUTRALS.has(a) ? 0.85 : 0.6;
    if (isPair(a, b)) return 0.95;
    if (NEUTRALS.has(a) && NEUTRALS.has(b)) return 0.9;
    if (NEUTRALS.has(a) || NEUTRALS.has(b)) return 0.85;
    return 0.3;
  }

