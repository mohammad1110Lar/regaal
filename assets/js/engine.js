  function search(query, prevIntent, opts) {
    opts = opts || {};
    reshuffle();
    const parsed = parse(query);
    let intent = dropFrom(mergeIntent(parsed, prevIntent), opts.drop);
    // کلید خانم/آقا فقط وقتی اعمال می‌شود که متن خودش جنسیت نگفته باشد
    const genderFromToggle = !parsed.genders.length && !!opts.gender && !intent.genderDropped;
    if (genderFromToggle) intent = Object.assign({}, intent, { genders: [opts.gender] });
    // پاسخ‌های مشاوره (سبک، رنگ، سایز، سن، بودجه…)؛ بعد دوباره حذف‌های کاربر
    if (opts.profile) intent = dropFrom(applyProfile(intent, opts.profile), opts.drop);
    intent.nowSeason = currentSeason();
    const empty = !hasContent(intent) && !intent.accOnly && !intent.cheap && !intent.sale && !intent.priceMax && !intent.wantLook && !parsed.genders.length && !intent.refined;
    if (empty) {
      return { intent, empty: true, title: "از کجا شروع کنیم؟", line: "بنویسید کجا می‌روید، چه حسی می‌خواهید یا دنبال چه لباسی هستید؛ بقیه‌اش با من.", message: "", results: [], look: [], accessories: [], story: [], tips: [], more: [], followups: ideas(opts.gender).slice(0, 4) };
    }

    const group = intent.accOnly || (intent.types.length && intent.types.every((t) => ACCESSORY_TYPES.includes(t))) ? "accessory" :
      intent.types.length || intent.occasion === "gift" ? null : "apparel";
    let scored = rankScored(intent, { group });
    // اگر نتیجه‌ای نبود، قیدها را مرحله‌به‌مرحله شل کن
    const relaxations = [{ colors: [], colorMood: null }, { fits: [], prefFits: [], patterns: [], materials: [] }, { keywords: [] }, { priceMax: null, sale: false }];
    let relaxed = 0;
    while (scored.length < 4 && relaxed < relaxations.length) {
      intent = Object.assign({}, intent, relaxations[relaxed++]);
      scored = rankScored(intent, { group });
    }
    if (!scored.length && intent.types.length) scored = rankScored(Object.assign({}, intent, { occasion: null }), { group, strictTypes: false, loose: true });
    // رنگ محبوب: تکه‌ی اصلی و چند نتیجه‌ی اول از همان رنگ (اگر برای این موقعیت مناسب است و موجود است)
    const liked = group === "accessory" ? { list: scored.map((x) => x[1]), found: null } : likeFirst(scored, intent);
    let pool = liked.list;
    intent.likeUnsuitable = unsuitableColors(intent);
    intent.likeFound = liked.found;
    // نوع مشخص (مثلاً «کاپشن زیر ۵ میلیون») مهم‌تر از بودجه است: اگر در بودجه نبود، ارزان‌ترین‌های همان نوع
    let note = "";
    if (intent.types.length && intent.priceMax && pool.filter((x) => intent.types.includes(x.type)).length < 3) {
      const wider = rank(Object.assign({}, intent, { priceMax: null, cheap: true }), { group }).filter((x) => intent.types.includes(x.type));
      if (wider.length) {
        note = intent.types.map((t) => TYPE_LABEL[t]).join(" و ") + " در این بودجه موجود نبود؛ ارزان‌ترین‌های موجود را آوردم.";
        pool = wider.sort((a, b) => a.price - b.price).concat(pool.filter((x) => !wider.includes(x)));
      }
    }

    const perType = intent.types.length === 1 ? 0 : intent.occasion === "gift" ? 2 : intent.occasion || !intent.types.length ? 3 : 0;
    const results = diversify(pool, 10, perType);
    // صادقانه بگو اگر از نوع خواسته‌شده در سایز کاربر کم مانده
    if (intent.size) intent.types.filter((t) => !ACCESSORY_TYPES.includes(t)).forEach((t) => {
      const inSize = results.filter((x) => x.type === t).length;
      const inStock = ITEMS.filter((x) => x.type === t && (!intent.genders.length || intent.genders.includes(x.gender))).length;
      if (inSize < 3 && inStock > inSize) note = (note ? note + " " : "") + "از " + TYPE_LABEL[t] + " فقط " + faNum(inSize) + " مدل در سایز " + intent.size.letter + "\u200f شما موجود است.";
    });
    const lookAnchor = group === "accessory" || intent.occasion === "gift" ? null : results.find((x) => !x._acc);
    intent.likeAnchor = !!(lookAnchor && liked.found && (intent.likeColors || []).includes(lookAnchor._fam));
    const look = lookAnchor ? buildLook(lookAnchor, intent) : [];
    let dressed = intent.noAcc ? [] : dressAccessories(look.length ? look : results.slice(0, 1), intent, 5).filter((d) => !results.includes(d.item));
    // بودجه‌ی کل: اکسسوری‌ها تا جایی که در بودجه جا شوند؛ وگرنه گزینه‌ی ارزان‌تر هم‌حس
    if (intent.budget) {
      let total = look.reduce((sum, x) => sum + x.price, 0);
      if (total > intent.budget) note = (note ? note + " " : "") + "جمع لباس‌ها کمی از بودجه بیشتر شد؛ ارزان‌ترین ترکیب هماهنگ را آوردم.";
      dressed = dressed.reduce((out, d) => {
        if (total + d.item.price <= intent.budget) { total += d.item.price; out.push(d); return out; }
        const alt = d.alts.map((id) => BY_ID.get(id)).filter((x) => x && !x._minor && total + x.price <= intent.budget).sort((a, b) => a.price - b.price)[0];
        if (alt) { total += alt.price; out.push(Object.assign({}, d, { item: alt, alts: d.alts.filter((id) => id !== alt.id).concat(d.item.id), note: "هم‌حس با بقیه‌ی استایل و در بودجه‌ی شما." })); }
        return out;
      }, []);
    }
    const accessories = dressed.map((d) => d.item);
    const more = diversify(pool.filter((x) => !results.includes(x)), 12, perType);
    const loose = !hasContent(intent) && !intent.genders.length && !intent.cheap && !intent.sale && !intent.priceMax;

    return {
      intent, relaxed: relaxed > 0, title: titleFor(intent, results), line: lineFor(intent, results, loose),
      understood: understandingOf(intent, { genderFromToggle }),
      message: messageFor(intent, results, look, accessories, ITEMS.length, loose, [note].concat(personalNotes(intent)).filter(Boolean).join(" ")),
      results, look, accessories, story: look.length ? storyOf(look, dressed, intent) : [], tips: look.length ? tipsFor(intent, look, accessories) : [],
      more, followups: followupsFor(intent, results), budget: intent.budget || null, size: intent.size || null,
      candidates: pool.slice(0, 120).map((x) => x.id),
    };
  }

