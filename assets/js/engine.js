  function toneScore(it, slot, ctx) {
    const f = it._fam;
    const tone = slot.tone || "soft";
    const lookFams = ctx.look.map((x) => x._fam).filter(Boolean);
    const neutralOutfit = lookFams.every((x) => NEUTRALS.has(x));
    if (tone.startsWith("match:")) {
      const ref = ctx.chosen[tone.slice(6)];
      if (!ref) return toneScore(it, Object.assign({}, slot, { tone: "classic" }), ctx);
      if (leatherTone(ref._fam) && leatherTone(ref._fam) === leatherTone(f)) return 1;
      if (ref._fam === f) return 1;
      return NEUTRALS.has(f) && NEUTRALS.has(ref._fam) ? 0.45 : 0.15;
    }
    switch (tone) {
      case "classic": return ["black", "brown", "cream", "navy"].includes(f) ? 1 : f === "grey" ? 0.7 : 0.3;
      case "dark": return it._dark || ["black", "navy", "brown"].includes(f) ? 1 : f === "grey" ? 0.6 : 0.2;
      case "black": return f === "black" ? 1 : ["navy", "grey"].includes(f) && it._dark ? 0.5 : 0;
      case "light": return it._light || ["white", "cream", "pink", "yellow"].includes(f) ? 1 : 0.35;
      case "fresh": return ["white", "cream", "green", "pink", "blue", "yellow", "purple"].includes(f) && !it._dark ? 1 : 0.35;
      case "festive": return ["red", "green"].includes(f) ? 1 : neutralOutfit ? 0.25 : 0.6;
      case "autumn": return ["brown", "yellow", "red", "orange", "green", "cream"].includes(f) ? 1 : 0.4;
      case "accent":
        if (neutralOutfit) return f && !NEUTRALS.has(f) ? (ctx.palette && ctx.palette.includes(f) ? 1 : 0.9) : 0.5;
        return NEUTRALS.has(f) ? 1 : lookFams.includes(f) ? 0.75 : 0.2;
      case "metal": {
        const cool = lookFams.filter((x) => COOL.has(x)).length >= lookFams.length / 2;
        if (!it._metal) return 0.6;
        return (cool && it._metal === "silver") || (!cool && it._metal === "gold") ? 1 : 0.5;
      }
      default: // soft: هم‌خانواده یا خنثی کنار لباس
        return lookFams.length ? Math.max(...lookFams.map((x) => harmony(x, f))) : 0.6;
    }
  }

  function slotScore(it, slot, ctx) {
    let s = 0;
    const doc = it._doc;
    const p = slot.prefer.filter((w) => doc.includes(normalize(w))).length;
    s += Math.min(p, 2) * 16;
    if (slot.avoid.some((w) => doc.includes(normalize(w)))) s -= 40;
    s += toneScore(it, slot, ctx) * 44;
    const season = ctx.intent.season || ctx.intent.nowSeason;
    if (season === "warm" && it._cold && !it._warm) s -= 22;
    if (season === "cold" && it._warm && !it._cold) s -= 22;
    if (it._minor && ctx.intent.occasion !== "gift") s -= 45;
    if (ctx.intent.priceMax && it.price > ctx.intent.priceMax) s -= 10;
    if (ctx.like && ctx.like.includes(it._fam)) s += 12;
    s += Math.min(it.orders || 0, 60) / 15 + (it.discount || 0) / 40;
    return s - seenPenalty(it) * 0.6 + jitter(it) * 6;
  }

